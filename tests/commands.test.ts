import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { describe, test } from "node:test";
import { pluginRoot } from "../plugins/script-forge/lib/paths.ts";

function read(name: string): string {
	return readFileSync(join(pluginRoot(), name), "utf8");
}

describe("generated commands", () => {
	test("Claude commands use npx and pass userConfig", () => {
		const content = read(join("commands", "scaffold.md"));
		assert.ok(content.includes("user-invocable: true"));
		assert.ok(content.includes("allowed-tools: Bash(npx:*)"));
		assert.ok(content.includes("$ARGUMENTS"));
		assert.ok(content.includes("--claude-config-json"));
		assert.ok(content.includes("${user_config.defaultNamespace}"));
		assert.ok(content.includes("<!-- generated by glowing-trefoil -->"));
	});

	test("Cursor commands use natural language and no Claude config", () => {
		const content = read(join("commands-cursor", "scaffold.md"));
		assert.ok(content.includes("name: \"script-forge-scaffold\""));
		assert.ok(content.includes("npx -y glowing-trefoil scaffold"));
		assert.ok(!content.includes("${user_config"));
		assert.ok(content.includes("<!-- generated by glowing-trefoil -->"));
	});

	test("OpenCode commands are flat and use $ARGUMENTS", () => {
		const content = read(join("commands-opencode", "script-forge-lint.md"));
		assert.ok(content.includes("$ARGUMENTS"));
		assert.ok(content.includes("npx -y glowing-trefoil lint"));
		assert.ok(!content.includes("${user_config"));
	});

	test("no source placeholder leaks into generated files", () => {
		const names = [
			join("commands", "doctor.md"),
			join("commands-cursor", "doctor.md"),
			join("commands-opencode", "script-forge-doctor.md"),
		];
		for (const name of names) {
			assert.ok(!read(name).includes("{{invocation}}"));
		}
	});
});
