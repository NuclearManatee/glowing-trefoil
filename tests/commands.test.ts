import { describe, expect, test } from "bun:test";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { pluginRoot } from "../plugins/script-forge/lib/paths.ts";

function read(name: string): string {
	return readFileSync(join(pluginRoot(), name), "utf8");
}

describe("generated commands", () => {
	test("Claude commands use npx and pass userConfig", () => {
		const content = read(join("commands", "scaffold.md"));
		expect(content).toContain("user-invocable: true");
		expect(content).toContain("allowed-tools: Bash(npx:*)");
		expect(content).toContain("$ARGUMENTS");
		expect(content).toContain("--claude-config-json");
		expect(content).toContain("${user_config.defaultNamespace}");
		expect(content).toContain("<!-- generated by glowing-trefoil -->");
	});

	test("Cursor commands use natural language and no Claude config", () => {
		const content = read(join("commands-cursor", "scaffold.md"));
		expect(content).toContain("name: \"script-forge-scaffold\"");
		expect(content).toContain("npx -y glowing-trefoil scaffold");
		expect(content).not.toContain("${user_config");
		expect(content).toContain("<!-- generated by glowing-trefoil -->");
	});

	test("OpenCode commands are flat and use $ARGUMENTS", () => {
		const content = read(join("commands-opencode", "script-forge-lint.md"));
		expect(content).toContain("$ARGUMENTS");
		expect(content).toContain("npx -y glowing-trefoil lint");
		expect(content).not.toContain("${user_config");
	});

	test("no source placeholder leaks into generated files", () => {
		const names = [
			join("commands", "doctor.md"),
			join("commands-cursor", "doctor.md"),
			join("commands-opencode", "script-forge-doctor.md"),
		];
		for (const name of names) {
			expect(read(name)).not.toContain("{{invocation}}");
		}
	});
});
