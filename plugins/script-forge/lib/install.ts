import { cpSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { dirname, join } from "node:path";
import { internalError, userError } from "./errors.ts";
import { packageVersion, pluginRoot, skillsDir } from "./paths.ts";

export const MARKER_FILE = ".glowing-trefoil.json";
export const FILE_MARKER = "<!-- generated by glowing-trefoil -->";

const OPENCODE_COMMAND_NAMES = [
	"script-forge-scaffold.md",
	"script-forge-doctor.md",
	"script-forge-lint.md",
] as const;

export type InstallTarget = "cursor" | "opencode";

export type InstallOptions = {
	homeDir?: string;
	force: boolean;
};

export type InstallResult = {
	target: InstallTarget;
	paths: string[];
};

type Marker = {
	package: string;
	plugin: string;
	version: string;
	kind: string;
	installedAt: string;
};

function markerFor(kind: string): Marker {
	return {
		package: "glowing-trefoil",
		plugin: "script-forge",
		version: packageVersion(),
		kind,
		installedAt: new Date().toISOString(),
	};
}

function writeMarker(directory: string, kind: string): void {
	mkdirSync(directory, { recursive: true });
	writeFileSync(join(directory, MARKER_FILE), `${JSON.stringify(markerFor(kind), null, "\t")}\n`, "utf8");
}

function isOwnedDirectory(directory: string): boolean {
	const markerPath = join(directory, MARKER_FILE);
	if (!existsSync(markerPath)) {
		return false;
	}
	try {
		const parsed = JSON.parse(readFileSync(markerPath, "utf8")) as Partial<Marker>;
		return parsed.package === "glowing-trefoil" && parsed.plugin === "script-forge";
	} catch {
		return false;
	}
}

function isOwnedFile(path: string): boolean {
	if (!existsSync(path)) {
		return false;
	}
	try {
		return readFileSync(path, "utf8").includes(FILE_MARKER);
	} catch {
		return false;
	}
}

function assertCanReplaceDirectory(directory: string, force: boolean): void {
	if (existsSync(directory) && !isOwnedDirectory(directory) && !force) {
		throw userError(`refusing to overwrite ${directory}: not installed by glowing-trefoil (pass --force to replace)`);
	}
}

function assertCanReplaceFile(path: string, force: boolean): void {
	if (existsSync(path) && !isOwnedFile(path) && !force) {
		throw userError(`refusing to overwrite ${path}: not generated by glowing-trefoil (pass --force to replace)`);
	}
}

function cursorDirectory(homeDir: string): string {
	return join(homeDir, ".cursor", "plugins", "local", "script-forge");
}

function openCodeCommandsDirectory(homeDir: string): string {
	return join(homeDir, ".config", "opencode", "commands");
}

function openCodeSkillDirectory(homeDir: string): string {
	return join(homeDir, ".agents", "skills", "anvil");
}

export function installCursor(options: InstallOptions): InstallResult {
	const homeDir = options.homeDir ?? homedir();
	const destination = cursorDirectory(homeDir);
	assertCanReplaceDirectory(destination, options.force);
	if (existsSync(destination)) {
		rmSync(destination, { recursive: true, force: true });
	}
	mkdirSync(dirname(destination), { recursive: true });
	cpSync(pluginRoot(), destination, { recursive: true, force: true });
	writeMarker(destination, "cursor-plugin");
	return { target: "cursor", paths: [destination] };
}

export function uninstallCursor(options: InstallOptions): InstallResult {
	const homeDir = options.homeDir ?? homedir();
	const destination = cursorDirectory(homeDir);
	if (!existsSync(destination)) {
		throw userError(`nothing to uninstall at ${destination}`);
	}
	assertCanReplaceDirectory(destination, options.force);
	rmSync(destination, { recursive: true, force: true });
	return { target: "cursor", paths: [destination] };
}

export function installOpenCode(options: InstallOptions): InstallResult {
	const homeDir = options.homeDir ?? homedir();
	const commandsDir = openCodeCommandsDirectory(homeDir);
	const skillDestination = openCodeSkillDirectory(homeDir);
	const sourceCommandsDir = join(pluginRoot(), "commands-opencode");
	if (!existsSync(sourceCommandsDir)) {
		throw internalError("commands-opencode/ is missing from the package");
	}
	const sourceNames = readdirSync(sourceCommandsDir).filter((name) => name.endsWith(".md"));
	const commandPaths = OPENCODE_COMMAND_NAMES.map((name) => join(commandsDir, name));

	for (const name of sourceNames) {
		if (!OPENCODE_COMMAND_NAMES.includes(name as (typeof OPENCODE_COMMAND_NAMES)[number])) {
			throw internalError(`unexpected OpenCode command file: ${name}`);
		}
	}
	for (const path of commandPaths) {
		assertCanReplaceFile(path, options.force);
	}
	assertCanReplaceDirectory(skillDestination, options.force);

	mkdirSync(commandsDir, { recursive: true });
	for (const name of OPENCODE_COMMAND_NAMES) {
		const source = join(sourceCommandsDir, name);
		if (!existsSync(source)) {
			throw internalError(`missing generated command: ${name}`);
		}
		const content = readFileSync(source, "utf8");
		if (!content.includes(FILE_MARKER)) {
			throw internalError(`generated command is missing its marker: ${name}`);
		}
		writeFileSync(join(commandsDir, name), content, "utf8");
	}

	if (existsSync(skillDestination)) {
		rmSync(skillDestination, { recursive: true, force: true });
	}
	mkdirSync(dirname(skillDestination), { recursive: true });
	cpSync(join(skillsDir(), "anvil"), skillDestination, { recursive: true, force: true });
	writeMarker(skillDestination, "opencode-skill");

	return {
		target: "opencode",
		paths: [...commandPaths, skillDestination],
	};
}

export function uninstallOpenCode(options: InstallOptions): InstallResult {
	const homeDir = options.homeDir ?? homedir();
	const commandsDir = openCodeCommandsDirectory(homeDir);
	const skillDestination = openCodeSkillDirectory(homeDir);
	const commandPaths = OPENCODE_COMMAND_NAMES.map((name) => join(commandsDir, name));
	const existingCommands = commandPaths.filter((path) => existsSync(path));
	const skillExisted = existsSync(skillDestination);

	for (const path of existingCommands) {
		assertCanReplaceFile(path, options.force);
	}
	if (skillExisted) {
		assertCanReplaceDirectory(skillDestination, options.force);
	}

	for (const path of existingCommands) {
		rmSync(path, { force: true });
	}
	if (skillExisted) {
		rmSync(skillDestination, { recursive: true, force: true });
	}

	return {
		target: "opencode",
		paths: [...existingCommands, ...(skillExisted ? [skillDestination] : [])],
	};
}
